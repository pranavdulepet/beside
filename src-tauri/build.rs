fn main() {
    println!("cargo:rerun-if-changed=native.m");
    println!("cargo:rerun-if-changed=activity.m");
    println!("cargo:rerun-if-changed=bag_vision.m");
    println!("cargo:rerun-if-changed=meeting.m");
    println!("cargo:rerun-if-changed=voice.m");
    println!("cargo:rerun-if-changed=overlay.m");
    println!("cargo:rerun-if-changed=calendar.m");
    cc::Build::new()
        .file("calendar.m")
        .file("native.m")
        .file("activity.m")
        .file("bag_vision.m")
        .file("meeting.m")
        .file("voice.m")
        .file("overlay.m")
        .flag("-fobjc-arc")
        .flag("-Wno-incompatible-pointer-types")
        .compile("beside_native");
    for name in [
        "Foundation",
        "EventKit",
        "Vision",
        "AVFoundation",
        "CoreMedia",
        "Speech",
        "Carbon",
        "ScreenCaptureKit",
        "ServiceManagement",
        "ImageIO",
        "AppKit",
        "WebKit",
        "QuartzCore",
        "PDFKit",
        "NaturalLanguage",
        "ApplicationServices",
        "IOKit",
        "UserNotifications",
    ] {
        println!("cargo:rustc-link-lib=framework={name}");
    }
    tauri_build::build()
}
